#!/usr/bin/env python3
"""Generate the CONTROL_SPEC §8 golden fixture (PowerShell-safe, stdlib only).

The fixture is the *contract* between the Python reference implementation and the
C++ core. It is deliberately plant-free: ``y`` is a prescribed signal, so a
mismatch can only come from the regulator itself, never from a physics port.

    cd sim/python && PYTHONPATH=. python3 ../../tests/golden/generate_golden.py

Writes ``step_response_case.csv`` next to this file. Do not hand-edit it; rerun.
"""

from __future__ import annotations

import csv
import math
from pathlib import Path

import numpy as np

from pistr_sim.control.str import STR, STRConfig
from pistr_sim.params import default_params

HERE = Path(__file__).resolve().parent
FIXTURE = HERE / "step_response_case.csv"

# --- §8 scenario constants (normative; keep in sync with CONTROL_SPEC §8) ----
ORDER = 2
H = 0.04
T_END = 3.0
ZETA, WN, MU = 0.7, 5.0, 0.0
LAMBDA, PMAX, PERCENT = 0.99, 5.0, 0.75
U_MAX = 50.0
STEP_TIME, STEP_VALUE = 1.0, 0.5  # rad/s
SINE_DELAY = 0.1  # rad/s offset so the RLS sees excitation from tick 0


def y_desired(t: float) -> float:
    return STEP_VALUE if t >= STEP_TIME - 1e-12 else 0.0


def y_measured(t: float) -> float:
    """Prescribed measured rate: a bounded 0.7 Hz sinusoid plus a small offset."""
    return 0.4 * math.sin(2.0 * math.pi * 0.7 * t) + SINE_DELAY


def main() -> int:
    params = default_params("paper")
    cfg = STRConfig.mode_ii(params, channel=0, y_unit="rad", percent=PERCENT)
    cfg = cfg.with_(h=H, zeta=ZETA, wn=WN, mu=MU, forgetting=LAMBDA,
                    p_max=PMAX, u_max=U_MAX, u_min=-U_MAX, order=ORDER)
    reg = STR(cfg)
    theta0 = np.asarray(cfg.theta0, dtype=float)
    assert theta0.size == 2 * ORDER, theta0

    n = int(round(T_END / H))
    rows = []
    for k in range(n):
        t = k * H
        yd, y = y_desired(t), y_measured(t)
        # keep the trace file small: the plant is prescribed, not simulated
        u_design = float(reg.step(yd, y))
        u_cmd = float(np.clip(u_design, -U_MAX, U_MAX))
        reg.ack(u_cmd)
        rows.append((t, yd, y, u_cmd, u_design, u_cmd, *reg.theta_hat))

    with FIXTURE.open("w", newline="", encoding="utf-8") as fh:
        fh.write("# generated by tests/golden/generate_golden.py -- do not edit by hand\n")
        fh.write(f"# spec: docs/CONTROL_SPEC.md §8  schema: 2  order: {ORDER}\n")
        fh.write(
            "# config: "
            f"h={H} zeta={ZETA} wn={WN} mu={MU} lambda={LAMBDA} pmax={PMAX} "
            f"percent={PERCENT} umax={U_MAX}\n"
        )
        fh.write("# theta0=" + ",".join(f"{v:.17g}" for v in theta0) + "\n")
        fh.write(
            "# plant: none (y is prescribed); y(t) = 0.4*sin(2*pi*0.7*t) + 0.1, "
            f"y_des step to {STEP_VALUE} at t={STEP_TIME}\n"
        )
        fh.write("# tolerance_rel=1e-9\n")
        w = csv.writer(fh)
        w.writerow(["t", "y_des", "y", "u_actual", "u_design", "u_cmd",
                    "theta0", "theta1", "theta2", "theta3"])
        for row in rows:
            w.writerow([f"{v:.17g}" for v in row])

    print(f"wrote {FIXTURE} ({len(rows)} ticks, theta0={np.round(theta0, 6).tolist()})")
    print(f"u range [{min(r[4] for r in rows):.4f}, {max(r[4] for r in rows):.4f}] "
          f"(clamped to +/-{U_MAX})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
